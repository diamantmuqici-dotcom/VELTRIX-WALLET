#!/usr/bin/env python3
"""Generate the Zig asset table that gets embedded into the desktop launcher.

    tools/gen-win-assets.py <dist dir> <out dir>

Copies every file under `<dist dir>` into `<out dir>/www/` and writes
`<out dir>/assets.zig`, which `@embedFile`s each of them. The launcher serves
only from this fixed table — it never touches the filesystem at request time,
so a request path cannot escape into one.
"""

from __future__ import annotations

import os
import shutil
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".ttf": "font/ttf",
    ".map": "application/json; charset=utf-8",
    ".txt": "text/plain; charset=utf-8",
    ".wasm": "application/wasm",
}

HEADER = """// Generated by tools/gen-win-assets.py — do not edit.
//
// Every file the desktop launcher can serve, compiled into the executable.

const std = @import("std");

pub const Asset = struct {
    path: []const u8,
    mime: []const u8,
    bytes: []const u8,
};

pub const list = [_]Asset{
"""

FOOTER = """};

pub fn find(path: []const u8) ?Asset {
    for (list) |a| {
        if (std.mem.eql(u8, a.path, path)) return a;
    }
    return null;
}
"""


def zig_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2

    dist, out = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
    www = os.path.join(out, "www")

    if not os.path.isdir(dist):
        print(f"error: no such dist directory: {dist}", file=sys.stderr)
        return 1

    if os.path.isdir(www):
        shutil.rmtree(www)
    os.makedirs(www, exist_ok=True)

    entries: list[tuple[str, str, int]] = []
    for root, dirs, files in os.walk(dist):
        dirs.sort()
        for name in sorted(files):
            src = os.path.join(root, name)
            rel = os.path.relpath(src, dist).replace(os.sep, "/")
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME:
                print(f"error: no MIME type for '{rel}' — add it to MIME", file=sys.stderr)
                return 1
            dest = os.path.join(www, rel)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copy2(src, dest)
            entries.append((rel, MIME[ext], os.path.getsize(src)))

    if not any(rel == "index.html" for rel, _, _ in entries):
        print("error: dist has no index.html", file=sys.stderr)
        return 1

    entries.sort(key=lambda e: (e[0] != "index.html", e[0]))

    lines = [HEADER]
    for rel, mime, size in entries:
        lines.append(
            f"    .{{ .path = {zig_str('/' + rel)}, .mime = {zig_str(mime)}, "
            f".bytes = @embedFile({zig_str('www/' + rel)}) }}, // {size} B\n"
        )
    lines.append(FOOTER)

    with open(os.path.join(out, "assets.zig"), "w", encoding="utf-8") as fh:
        fh.write("".join(lines))

    total = sum(size for _, _, size in entries)
    print(f"assets.zig: {len(entries)} file(s), {total:,} B embedded")
    for rel, mime, size in entries:
        print(f"  /{rel:<52} {mime:<32} {size:>9,} B")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
